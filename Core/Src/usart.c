//中断回调函数，接收中断发生后，把接收到的数据RES存入modbus.rcbuf[]
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart){
	//USART1接收中断
	if (huart == &huart1){
		if(modbus.reflag == 1)  //有数据包正在处理
 	    {
			return ;
 		}		
 	    modbus.rcbuf[modbus.recount++] = RES;
 		modbus.timout = 0;
 		if(modbus.recount == 1)  //已经收到了第二个字节的数据
 		{
 		  modbus.timrun = 1;  //开启modbus定时器计时
 		}		
		HAL_UART_Receive_IT(&huart1, (uint8_t *)&RES, 1);//重新打开中断接收，为下次接收数据做准备
	}
}


